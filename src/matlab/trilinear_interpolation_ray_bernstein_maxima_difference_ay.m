clc,clear

% pkg load symbolic % OCTAVE version
% pkg load optim % OCTAVE version

%% --------------------------------------------------------------------
%% Declare symbols
%% --------------------------------------------------------------------

% corner values
% symmetric linear combinations of corner values
syms f000 f100 f010 f001 f011 f101 f110 f111 real
syms v000 v100 v010 v001 v011 v101 v110 v111 real

F = [f000 f100 f010 f001 f011 f101 f110 f111];
V = [v000 v100 v010 v001 v011 v101 v110 v111];

F2V = [
    v000, ...
    v100 + v000, ...
    v010 + v000, ...
    v001 + v000, ...
    v011 + v001 + v010 + v000, ...
    v101 + v001 + v100 + v000, ...
    v110 + v010 + v100 + v000, ...
    v111 + v011 + v101 + v110 + v100 + v010 + v001 + v000, ...
];

V2F = [
    f000, ...
    f100 - f000, ...
    f010 - f000, ...
    f001 - f000, ...
    f000 - f001 - f010 + f011, ...
    f000 - f001 - f100 + f101, ...
    f000 - f010 - f100 + f110, ...
    f001 - f000 + f010 - f011 + f100 - f101 - f110 + f111, ...
];

% Variables
syms x y z t real
r = [x, y, z];

% Ray endpoints
syms ax ay az bx by bz dx dy dz sx sy sz real
a = [ax, ay, az];
b = [bx, by, bz];

%% --------------------------------------------------------------------
%% Trilinear interpolation f(x,y,z)
%% --------------------------------------------------------------------

f_xyz = f000 * (1-x) * (1-y) * (1-z) ...
      + f100 *    x  * (1-y) * (1-z) ...
      + f010 * (1-x) *    y  * (1-z) ...
      + f001 * (1-x) * (1-y) *    z  ...
      + f011 * (1-x) *    y  *    z  ...
      + f101 *    x  * (1-y) *    z  ...
      + f110 *    x  *    y  * (1-z) ...
      + f111 *    x  *    y  *    z;

%% --------------------------------------------------------------------
%% Ray substitution r(t) 
%% --------------------------------------------------------------------

x_t = ax*(1-t) + bx*t;
y_t = ay*(1-t) + by*t;
z_t = az*(1-t) + bz*t;

r_t = [x_t, y_t, z_t];

%% --------------------------------------------------------------------
%% Trilinear function over ray  
%% --------------------------------------------------------------------

f_t = simplify( subs(f_xyz, r, r_t) );
f_t = collect(f_t, t);

% Extract coefficients
[f_t_coeffs, f_t_terms] = coeffs(f_t, t);

%% --------------------------------------------------------------------
%% Bernstein Trilinear function over ray 
%% --------------------------------------------------------------------

% Bernstein coefficients
Bf_t_coeffs = [
    simplify(f_t_coeffs(4)), ...
    simplify(f_t_coeffs(4) + f_t_coeffs(3)*1/3), ...
    simplify(f_t_coeffs(4) + f_t_coeffs(3)*2/3 + f_t_coeffs(2)*1/3), ...
    simplify(f_t_coeffs(4) + f_t_coeffs(3) + f_t_coeffs(2) + f_t_coeffs(1)), ...
];

% Bernstein terms
Bf_t_terms = [ ...
    1 * t^0 * (1 - t)^3, ...
    3 * t^1 * (1 - t)^2, ...
    3 * t^2 * (1 - t)^1, ...
    1 * t^3 * (1 - t)^0, ...
];

% Bernstein trilinear function over ray
Bf_t = dot(Bf_t_coeffs, Bf_t_terms);

disp("Sanity check f(t) - Bf_t(t), should be 0:");
disp(simplify(f_t - Bf_t));

%% --------------------------------------------------------------------
%% Maxima of trilinear derivative over ray
%% --------------------------------------------------------------------

maxima_terms = [
    simplify(Bf_t_coeffs(2) - Bf_t_coeffs(1)), ...
    simplify(Bf_t_coeffs(3) - Bf_t_coeffs(1)), ...
    simplify(Bf_t_coeffs(4) - Bf_t_coeffs(1)), ...
];

maxima = [
    simplify(subs( maxima_terms(1), [a, b], [[0,0,0], [0,0,1]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[0,0,0], [0,1,1]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[0,0,0], [1,0,1]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[0,0,0], [1,1,1]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[1,0,0], [1,0,0]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[1,0,0], [1,0,1]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[1,0,0], [1,1,1]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[0,0,1], [0,0,1]]) ), ... 
    simplify(subs( maxima_terms(1), [a, b], [[1,0,1], [1,0,1]]) ), ... 
    
    simplify(subs( maxima_terms(2), [a, b], [[0,0,0], [0,0,1]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[0,0,0], [0,1,1]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[0,0,0], [1,0,1]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[0,0,0], [1,1,1]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[1,0,0], [1,0,0]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[1,0,0], [1,0,1]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[1,0,0], [1,1,1]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[0,0,1], [0,0,1]]) ), ...
    simplify(subs( maxima_terms(2), [a, b], [[1,0,1], [1,0,1]]) ), ...

    simplify(subs( maxima_terms(3), [a, b], [[0,0,0], [0,0,1]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[0,0,0], [0,1,1]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[0,0,0], [1,0,1]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[0,0,0], [1,1,1]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[1,0,0], [1,0,0]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[1,0,0], [1,0,1]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[1,0,0], [1,1,1]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[0,0,1], [0,0,1]]) ), ...
    simplify(subs( maxima_terms(3), [a, b], [[1,0,1], [1,0,1]]) ), ...
];

maxima = unique(maxima);
maxima = maxima(:);
maxima_reduced = reduceMaximaSubconvex(maxima, F, 1e-8, false);

fprintf('\nReduced symbolic total maxima:\n');
disp(maxima_reduced);

